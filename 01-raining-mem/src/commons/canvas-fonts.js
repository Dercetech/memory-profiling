const uppercaseGlyphs = Object.fromEntries(
  Object.entries(LOWERCASE_GLYPHS).map(([letter, glyph]) => [letter.toUpperCase(), glyph])
);

export const PIXEL_FONT = Object.freeze({
  ...LOWERCASE_GLYPHS,
  ...uppercaseGlyphs,
  ...DIGITS_AND_PUNCTUATION
});

export function drawPixelText(context, text, centerX, top, color = '#f7fbff') {
  const glyphWidth = 5;
  const letterSpacing = 1;
  const textWidth = text.length * (glyphWidth + letterSpacing) - letterSpacing;
  const left = Math.floor(centerX - textWidth / 2);

  context.fillStyle = color;

  for (let characterIndex = 0; characterIndex < text.length; characterIndex += 1) {
    const glyph = PIXEL_FONT[text[characterIndex]];
    if (!glyph) continue;

    for (let row = 0; row < glyph.length; row += 1) {
      for (let column = 0; column < glyph[row].length; column += 1) {
        if (glyph[row][column] === '1') {
          context.fillRect(
            left + characterIndex * (glyphWidth + letterSpacing) + column,
            top + row,
            1,
            1
          );
        }
      }
    }
  }
}
